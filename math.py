first_number = input("Enter the first number: ")
second_number = input("Enter the second number: ")
sum_result = float(first_number) + float(second_number)
print("The sum of", first_number, "and", second_number, "is:", sum_result)

subtraction_result = float(first_number) - float(second_number)
print("The difference between", first_number, "and", second_number, "is:", subtraction_result)
